import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const owner = process.env.OBSIDIAN_VAULT_OWNER || "Tonkic";
const repo = process.env.OBSIDIAN_VAULT_REPO || "tonkic-obsidian-vault";
const branch = process.env.OBSIDIAN_VAULT_BRANCH || "main";
const limit = Number(process.env.OBSIDIAN_BLOG_LIMIT || "0");
const outputFile = path.join("src", "data", "obsidian-blog.ts");
const token = process.env.VAULT_REPO_TOKEN || process.env.GITHUB_TOKEN || "";

const headers = {
  Accept: "application/vnd.github+json",
  "User-Agent": "tonkic-site-blog-sync",
  ...(token ? { Authorization: `Bearer ${token}` } : {}),
};

const api = async (url) => {
  const response = await fetch(url, { headers });
  if (!response.ok) {
    throw new Error(`GitHub API failed ${response.status}: ${url}`);
  }
  return response.json();
};

const raw = async (filePath) => {
  const url = `https://raw.githubusercontent.com/${owner}/${repo}/${branch}/${encodePath(filePath)}`;
  const response = await fetch(url, { headers });
  if (!response.ok) {
    throw new Error(`Raw fetch failed ${response.status}: ${filePath}`);
  }
  const bytes = await response.arrayBuffer();
  return new TextDecoder("utf-8", { fatal: false }).decode(bytes);
};

const encodePath = (value) => value.split("/").map(encodeURIComponent).join("/");

const slugify = (value) => {
  const ascii = value
    .normalize("NFKD")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
  return ascii || "note";
};

const stripFrontmatter = (content) => content.replace(/^---[\s\S]*?---\s*/m, "");

const frontmatterValue = (content, key) => {
  const match = content.match(new RegExp(`^${key}:\\s*(.+)$`, "m"));
  return match ? match[1].trim().replace(/^["']|["']$/g, "") : "";
};

const titleFromMarkdown = (content, filePath) => {
  const fmTitle = frontmatterValue(content, "title");
  if (fmTitle) return fmTitle;

  const heading = stripFrontmatter(content).match(/^#\s+(.+)$/m);
  if (heading) return heading[1].trim();

  return path.basename(filePath, ".md");
};

const dateFromMarkdown = (content) => {
  const fmDate = frontmatterValue(content, "date");
  if (fmDate) return fmDate.slice(0, 10);

  const match = content.match(/\b(20\d{2})[-/.](\d{1,2})[-/.](\d{1,2})\b/);
  if (!match) return "";
  const [, year, month, day] = match;
  return `${year}-${month.padStart(2, "0")}-${day.padStart(2, "0")}`;
};

const cleanMarkdownForSummary = (content) =>
  stripFrontmatter(content)
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/!\[\[[^\]]+\]\]/g, " ")
    .replace(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, "$2$1")
    .replace(/!\[[^\]]*\]\([^)]+\)/g, " ")
    .replace(/\[[^\]]+\]\(([^)]+)\)/g, " ")
    .replace(/[#>*_`~-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const summaryFromMarkdown = (content) => {
  const summary = frontmatterValue(content, "summary") || cleanMarkdownForSummary(content);
  return summary.length > 180 ? `${summary.slice(0, 180)}...` : summary || "Obsidian vault 同步笔记。";
};

const tagsFromPath = (filePath) =>
  filePath
    .split("/")
    .slice(0, -1)
    .filter((part) => part !== "pic")
    .slice(0, 4);

const normalizeContent = (content) =>
  stripFrontmatter(content)
    .replace(/\r\n/g, "\n")
    .replace(/!\[\[([^\]]+)\]\]/g, "[图片：$1]")
    .replace(/\[\[([^\]|]+)\|([^\]]+)\]\]/g, "$2")
    .replace(/\[\[([^\]]+)\]\]/g, "$1")
    .trim();

const toEntry = (filePath, content) => {
  const title = titleFromMarkdown(content, filePath);
  const hash = createHash("sha1").update(filePath).digest("hex").slice(0, 10);
  const nameSlug = slugify(path.basename(filePath, ".md"));
  const slug = nameSlug === "note" ? hash : `${hash}-${nameSlug}`;
  return {
    slug,
    title,
    date: dateFromMarkdown(content),
    type: "Blog",
    summary: summaryFromMarkdown(content),
    href: `/blog/${slug}`,
    tags: tagsFromPath(filePath),
    content: normalizeContent(content),
    sourcePath: filePath,
    sourceUrl: `https://github.com/${owner}/${repo}/blob/${branch}/${encodePath(filePath)}`,
  };
};

const serialize = (entries) => `import type { ContentEntry } from "./site";

// Generated by scripts/sync-obsidian-blog.mjs. Do not edit by hand.
export const obsidianBlogEntries: ContentEntry[] = ${JSON.stringify(entries, null, 2)};
`;

const main = async () => {
  const tree = await api(`https://api.github.com/repos/${owner}/${repo}/git/trees/${branch}?recursive=1`);
  const markdownFiles = tree.tree
    .filter((item) => item.type === "blob")
    .filter((item) => item.path.endsWith(".md"))
    .filter((item) => item.path !== "README.md")
    .filter((item) => !item.path.startsWith("pic/"))
    .sort((a, b) => a.path.localeCompare(b.path, "zh-Hans-CN"));

  const selectedFiles = limit > 0 ? markdownFiles.slice(0, limit) : markdownFiles;

  const entries = [];
  for (const file of selectedFiles) {
    const content = await raw(file.path);
    entries.push(toEntry(file.path, content));
  }

  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, serialize(entries), "utf8");
  console.log(`Synced ${entries.length} Obsidian notes from ${owner}/${repo}`);
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
